import pandas as pd
raw = pd.read_csv('data/processed/airsense_master_raw.csv', parse_dates=['timestamp'])
clean = pd.read_csv('data/processed/airsense_final.csv', parse_dates=['timestamp'])
poll = ['pm2_5','pm10','carbon_monoxide','nitrogen_dioxide','sulphur_dioxide','ozone','dust']
print('RAW_SHAPE', raw.shape)
print('CLEAN_SHAPE', clean.shape)
print('RAW_MISSING_PM25', raw['pm2_5'].isnull().sum())
print('CLEAN_MISSING_PM25', clean['pm2_5'].isnull().sum())
print('RAW_MAX_PM25', raw['pm2_5'].max())
print('CLEAN_MAX_PM25', clean['pm2_5'].max())
print('RAW_MEAN_PM25', raw['pm2_5'].mean())
print('CLEAN_MEAN_PM25', clean['pm2_5'].mean())
print('RAW_STD_PM25', raw['pm2_5'].std())
print('CLEAN_STD_PM25', clean['pm2_5'].std())
print('RAW_SKEW_PM25', raw['pm2_5'].skew())
print('CLEAN_SKEW_PM25', clean['pm2_5'].skew())
print('RAW_NEGATIVE_TOTAL', (raw[poll] < 0).sum().sum())
print('CLEAN_NEGATIVE_TOTAL', (clean[poll] < 0).sum().sum())
print('NO2_NEGATIVE', int((raw['nitrogen_dioxide'] < 0).sum()))
print('O3_NEGATIVE', int((raw['ozone'] < 0).sum()))
print('DUST_NEGATIVE', int((raw['dust'] < 0).sum()))
print('NULLS_RAW_BY_COL', raw[poll].isnull().sum().to_dict())
print('NULLS_CLEAN_BY_COL', clean[poll].isnull().sum().to_dict())
print('AQI_COUNTS_RAW', raw['aqi_category'].value_counts().to_dict())
print('AQI_COUNTS_CLEAN', clean['aqi_category'].value_counts().to_dict())
print('ENGINEERED', [c for c in clean.columns if c not in raw.columns])
print('DATE_RANGE', raw['timestamp'].min(), raw['timestamp'].max())
print('PM25_CORR_USAQI', clean['pm2_5'].corr(clean['us_aqi']))
print('PLI_CORR_USAQI', clean['pollution_load_index'].corr(clean['us_aqi']))
print('CITY_MEDIAN', clean.groupby('city')['pm2_5'].median().sort_values(ascending=False).to_dict())
print('HOURLY_PM25_PEAK', clean.groupby(clean['timestamp'].dt.hour)['pm2_5'].mean().sort_values(ascending=False).head(10).to_dict())
